"""Compact read views and exact, scoped drilldown over schema-2 source.

No source rewriting, engine queries, execution simulation or preview inspection.
Unknown native properties remain visible; only explicit boilerplate is omitted.
"""
import copy
import call_arguments
import parameter_defaults

from asset_text_codec import fields, unquote
from graph_hierarchy import graph_key, inspect_graphs


EDITOR_PROPERTIES = {'NodeGuid', 'NodePosX', 'NodePosY', 'NodeWidth', 'NodeHeight',
                     'bCommentBubblePinned', 'bCommentBubbleVisible', 'AdvancedPinDisplay'}
PIN_EDITOR_FIELDS = {'PersistentGuid', 'PinFriendlyName', 'PinToolTip', 'AutogeneratedDefaultValue'}
PIN_DEFAULTS = {
    'PinType.PinSubCategory': '""', 'PinType.PinSubCategoryObject': 'None',
    'PinType.PinSubCategoryMemberReference': '()', 'PinType.PinValueType': '()',
    'PinType.ContainerType': 'None', 'PinType.bIsReference': 'False',
    'PinType.bIsConst': 'False', 'PinType.bIsWeakPointer': 'False',
    'PinType.bIsUObjectWrapper': 'False', 'PinType.bSerializeAsSinglePrecisionFloat': 'False',
    'bAdvancedView': 'False', 'bDefaultValueIsIgnored': 'False',
    'bDefaultValueIsReadOnly': 'False', 'bHidden': 'False',
    'bNotConnectable': 'False', 'bOrphanedPin': 'False',
}
TYPE_NAMES = {
    'PinType.PinCategory': 'category', 'PinType.PinSubCategory': 'subcategory',
    'PinType.PinSubCategoryObject': 'object', 'PinType.ContainerType': 'container',
    'PinType.bIsReference': 'reference', 'PinType.bIsConst': 'const',
    'PinType.bIsWeakPointer': 'weak', 'PinType.bIsUObjectWrapper': 'objectWrapper',
    'PinType.bSerializeAsSinglePrecisionFloat': 'singlePrecision',
    'PinType.PinValueType': 'valueType', 'PinType.PinSubCategoryMemberReference': 'member',
}
MEMBER_FIELDS = {'FunctionReference', 'VariableReference', 'EventReference', 'DelegateReference'}


def native_value(value):
    # Native expressions (object paths, tuples, localized text) remain literal.
    return unquote(value) if isinstance(value, str) else value


def member_reference(value):
    if not isinstance(value, str) or not value.startswith('(') or not value.endswith(')'):
        return value
    try:
        result = fields(value[1:-1])
    except ValueError:
        return value
    # An unnamed reference may only be resolvable through its GUID: retain it.
    if native_value(result.get('MemberName', '')):
        result.pop('MemberGuid', None)
    return {k: native_value(v) for k, v in result.items()}


def properties(source):
    return {key: member_reference(value) if key in MEMBER_FIELDS else value
            for key, value in source.items() if key not in EDITOR_PROPERTIES}


def checked_graph(document, graph):
    """Do not silently omit malformed endpoints or guess missing definitions."""
    nodes, endpoints = {}, {}
    for node in graph['body']['nodes']:
        identity = node['id']
        if identity in nodes:
            raise ValueError('Duplicate node ID: ' + identity)
        nodes[identity] = node
        if node['kind'] not in document['classes']:
            raise ValueError('Missing class definition for node: ' + identity)
        for alias, pin in node['pins'].items():
            endpoint = identity + '.' + alias
            if not alias.startswith(('in:', 'out:')):
                raise ValueError('Invalid pin direction: ' + endpoint)
            if pin['type'] not in document['pinTemplates']:
                raise ValueError('Missing pin template: ' + endpoint)
            endpoints[endpoint] = (node, alias)
        if set(node.get('defaults', {})) - set(node['pins']):
            raise ValueError('Default refers to an unknown pin: ' + identity)
        call_arguments.validate(node, document['pinTemplates'])
        parameter_defaults.validate(node, document['pinTemplates'])
    seen = set()
    for link in graph['body']['links']:
        a, b = link['from'], link['to']
        if a not in endpoints or b not in endpoints:
            raise ValueError('Unresolved graph link: ' + str(link))
        if not endpoints[a][1].startswith('out:') or not endpoints[b][1].startswith('in:') or (a, b) in seen:
            raise ValueError('Invalid or duplicate graph link: ' + str(link))
        seen.add((a, b))
    return nodes, endpoints


def compact_pin(document, node, alias, connected):
    pin = node['pins'][alias]
    metadata = document['pinTemplates'][pin['type']]
    result, kind, extra = {}, {}, {}
    for key, value in metadata.items():
        if key in PIN_EDITOR_FIELDS or (key in PIN_DEFAULTS and value == PIN_DEFAULTS[key]):
            continue
        if key in TYPE_NAMES:
            kind[TYPE_NAMES[key]] = (value == 'True' if key.startswith('PinType.b') and value in ('True', 'False') else native_value(value))
        else:
            extra[key] = value
    result['type'] = kind
    if 'PinType.PinCategory' not in metadata:
        result['type']['category'] = 'unknown'
    if 'name' in pin:
        result['name'] = pin['name']
    if extra:
        result['metadata'] = extra
    # Output, connected and ignored defaults are stored metadata, not values
    # produced at runtime. Entry signatures expose them separately below.
    if alias.startswith('in:') and node['id'] + '.' + alias not in connected and metadata.get('bDefaultValueIsIgnored') != 'True':
        if alias in node.get('arguments', {}):
            result['override'] = node['arguments'][alias]
        elif alias in node.get('defaults', {}):
            result['default'] = node['defaults'][alias]
        elif call_arguments.governed(node, alias, document['pinTemplates']):
            result['argumentMode'] = 'declaration-default' if alias in node.get('declarationDefaults', {}) else 'required'
        for key in ('DefaultObject', 'DefaultTextValue'):
            if key in pin:
                result[key] = pin[key]
    cls = document['classes'][node['kind']]
    entry = cls == '/Script/BlueprintGraph.K2Node_FunctionEntry' or (
        cls == '/Script/BlueprintGraph.K2Node_Tunnel' and node.get('properties', {}).get('bCanHaveOutputs') == 'True')
    if entry and alias.startswith('out:'):
        if 'parameterDefaults' in node and parameter_defaults.supported(alias,metadata):
            if alias in node['parameterDefaults']:
                result['parameterDefault'] = node['parameterDefaults'][alias]
            else:
                result['required'] = True
        stored = {key: pin[key] for key in ('DefaultObject', 'DefaultTextValue') if key in pin}
        if alias in node.get('defaults', {}):
            stored['DefaultValue'] = node['defaults'][alias]
        if stored:
            result['signatureDefaults'] = stored
    return result


def compact_node(document, node, connected):
    result = dict(id=node['id'], kind=node['kind'])
    props = properties(node.get('properties', {}))
    if props:
        result['properties'] = props
    result['pins'] = {alias: compact_pin(document, node, alias, connected) for alias in node['pins']}
    if node.get('custom'):
        result['custom'] = node['custom']
    return result


def variable_context(document, nodes, compact=False):
    names = set()
    for node in nodes:
        reference = member_reference(node.get('properties', {}).get('VariableReference', ''))
        if not isinstance(reference, dict) or reference.get('MemberScope'):
            continue
        owner = reference.get('MemberParent', '')
        if reference.get('bSelfContext') == 'True' or document['asset'] + '.' in owner:
            names.add(reference.get('MemberName'))
    result = {}
    for variable in document.get('variables', []):
        name = native_value(variable.get('VarName', ''))
        if name not in names:
            continue
        declaration = {k: v for k, v in variable.items() if not compact or k != 'VarGuid'}
        result[name] = dict(declaration=declaration)
        if name in document.get('defaults', {}):
            result[name]['initialDefault'] = document['defaults'][name]
    return result


def inspect_source(document, selection=None, *, view='compact', node_ids=None, pin=None, context=None):
    """Default compact CLI view; full retains the existing inspect_graphs payload."""
    if view not in ('compact', 'full'):
        raise ValueError('Expected view compact or full')
    if (node_ids or pin is not None or view == 'full' or context) and selection is None:
        raise ValueError('Detail selectors require --graph')
    if pin is not None and (not node_ids or len(node_ids) != 1):
        raise ValueError('--pin requires exactly one --node')
    if node_ids and view == 'full':
        raise ValueError('Use --view full for the graph or --node for scoped raw details')
    if context and view == 'full':
        raise ValueError('--context requires a compact graph or scoped node/pin view')
    detail = inspect_graphs(document, selection)
    if selection is None or view == 'full':
        return copy.deepcopy(detail)
    graph = detail['graph']
    nodes, endpoints = checked_graph(document, graph)
    links = graph['body']['links']
    connected = {v for link in links for v in link.values()}
    header = {k: graph[k] for k in ('name', 'kind', 'owner') if k in graph}
    header['id'] = graph_key(graph)
    result = dict(asset=document['asset'], view='graph-compact', graph=header)
    # Counts and selection identities remain useful without full ancestor bodies.
    by_graph = {graph_key(g): g for g in document['graphs']}
    result['ancestors'] = [dict(graph=a['graph'], operation=compact_node(document, a['operation'],
        {v for link in by_graph[a['graph']['id']]['body']['links'] for v in link.values()}))
        for a in detail['ancestors']]
    result['children'] = detail['children']
    if node_ids:
        if len(set(node_ids)) != len(node_ids):
            raise ValueError('Select distinct node IDs')
        missing = set(node_ids) - nodes.keys()
        if missing:
            raise ValueError('Unknown node IDs in selected graph: ' + ', '.join(sorted(missing)))
        selected = [nodes[identity] for identity in node_ids]
        if pin is not None:
            node = selected[0]
            if pin not in node['pins']:
                raise ValueError('Unknown pin in selected node: ' + pin)
            endpoint = node['id'] + '.' + pin
            data = node['pins'][pin]
            result.update(view='pin-detail', node=node['id'], pin=pin, source=data,
                          template=document['pinTemplates'][data['type']])
            if pin in node.get('defaults', {}):
                result['storedDefault'] = node['defaults'][pin]
            if call_arguments.governed(node, pin, document['pinTemplates']):
                result['argument'] = dict(mode='override' if pin in node['arguments'] else 'declaration-default' if pin in node.get('declarationDefaults', {}) else 'required',
                    declaration=member_reference(node['properties'].get('FunctionReference', '')))
                if pin in node.get('declarationDefaults', {}):
                    result['argument']['declarationDefault'] = node['declarationDefaults'][pin]
                if pin in node['arguments']:
                    result['argument']['value'] = node['arguments'][pin]
            selected_endpoints = {endpoint}
        else:
            result.update(view='node-detail', nodes=selected,
                          classes={n['kind']: document['classes'][n['kind']] for n in selected},
                          pinTemplates={p['type']: document['pinTemplates'][p['type']] for n in selected for p in n['pins'].values()})
            selected_endpoints = {n['id'] + '.' + alias for n in selected for alias in n['pins']}
        result['links'] = [link for link in links if selected_endpoints.intersection(link.values())]
        adjacent = {v for link in result['links'] for v in link.values()} - selected_endpoints
        result['boundaryPins'] = {endpoint: compact_pin(document, *endpoints[endpoint], connected)
                                  for endpoint in sorted(adjacent)}
        result['variables'] = variable_context(document, selected)
    else:
        props = properties(graph.get('properties', {}))
        props.pop('GraphGuid', None)
        if props:
            result['graph']['properties'] = props
        result.update(nodes=[compact_node(document, n, connected) for n in nodes.values()], links=links,
                      classes=detail['classes'], variables=variable_context(document, nodes.values(), compact=True))
    if context:
        from graph_context import inspect_context
        result['context'] = inspect_context(document, graph, selected if node_ids else list(nodes.values()), context)
    result['readOnly'] = True
    return copy.deepcopy(result)
