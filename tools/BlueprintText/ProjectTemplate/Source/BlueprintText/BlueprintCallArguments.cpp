bool BlueprintCallArguments::IsArgument(const UEdGraphPin* Pin)
{
    if(!Pin || Pin->Direction!=EGPD_Input || Pin->ParentPin || Pin->SubPins.Num() ||
       Pin->PinType.IsContainer() || Pin->PinType.bIsReference || Pin->bDefaultValueIsIgnored ||
       Pin->bOrphanedPin || Pin->PinName==UEdGraphSchema_K2::PN_Self)return false;
    const FName Type=Pin->PinType.PinCategory;
    return Type==UEdGraphSchema_K2::PC_Int || Type==UEdGraphSchema_K2::PC_Int64 ||
        Type==UEdGraphSchema_K2::PC_Real || Type==UEdGraphSchema_K2::PC_Boolean || Type==UEdGraphSchema_K2::PC_String;
}

bool BlueprintCallArguments::DeclarationDefault(const UFunction* Function,FName Name,FString& Value)
{
    const FName Marker(OptionalParameters);
    if(Function->HasMetaData(Marker))
    {
        TArray<TSharedPtr<FJsonValue>> Names;
        if(!FJsonSerializer::Deserialize(TJsonReaderFactory<>::Create(Function->GetMetaData(Marker)),Names))return false;
        for(const auto& Item:Names)if(Item->AsString()==Name.ToString())
        {Value=Function->GetMetaData(Name);return true;}
        return false;
    }
    // C++ metadata distinguishes an explicitly empty default from no default.
    const FName CppKey(*(FString(CppDefaultPrefix)+Name.ToString()));
    if(Function->HasMetaData(CppKey)){Value=Function->GetMetaData(CppKey);return true;}
    Value=Function->GetMetaData(Name);
    // Legacy Blueprint user pins cannot distinguish absent and empty strings.
    // Empty defaults require an explicit parameterDefaults declaration.
    return !Value.IsEmpty();
}


bool BlueprintCallArguments::Apply(UK2Node_CallFunction* Call,const FJsonObject& Request,FString& Error)
{
    UFunction* Function=Call->GetTargetFunction();
    if(!Function){Error=TEXT("Argument declaration is unavailable.");return false;}
    const auto* Schema=GetDefault<UEdGraphSchema_K2>();
    for(const auto& Pair:Request.Values)
    {
        FString Value;
        if(!IsArgument(Call->FindPin(*Pair.Key,EGPD_Input)) || !Pair.Value->TryGetString(Value))
        {Error=FString::Printf(TEXT("Unsupported argument override: %s"),*Pair.Key);return false;}
    }
    for(UEdGraphPin* Pin:Call->Pins)if(IsArgument(Pin))
    {
        const FProperty* Param=FindFProperty<FProperty>(Function,Pin->PinName);FEdGraphPinType Type;
        if(!Param || !Param->HasAnyPropertyFlags(CPF_Parm) || Param->HasAnyPropertyFlags(CPF_OutParm) ||
           !Schema->ConvertPropertyToPinType(Param,Type) || Type!=Pin->PinType)
        {Error=TEXT("Argument no longer matches its declaration: ")+Pin->PinName.ToString();return false;}
        FString Declared,Explicit;
        const bool HasDefault=DeclarationDefault(Function,Pin->PinName,Declared);
        const bool HasOverride=Request.TryGetStringField(Pin->PinName.ToString(),Explicit);
        if(!HasDefault && !HasOverride && Pin->LinkedTo.IsEmpty())
        {Error=TEXT("Missing required argument (no declaration default): ")+Pin->PinName.ToString();return false;}
        if(HasDefault)Schema->SetPinAutogeneratedDefaultValue(Pin,Declared);
        else Schema->SetPinAutogeneratedDefaultValueBasedOnType(Pin);
        if(HasOverride)Schema->GetPinDefaultValuesFromString(Pin->PinType,Call,Explicit,
            Pin->DefaultValue,Pin->DefaultObject,Pin->DefaultTextValue);
        const FString Invalid=Schema->IsPinDefaultValid(Pin,Pin->DefaultValue,Pin->DefaultObject,Pin->DefaultTextValue);
        if(!Invalid.IsEmpty()){Error=TEXT("Invalid argument: ")+Pin->PinName.ToString()+TEXT(". ")+Invalid;return false;}
    }
    return true;
}
TSharedRef<FJsonObject> BlueprintCallArguments::Snapshot(UK2Node_CallFunction* Call)
{
    auto Result=MakeShared<FJsonObject>();auto Values=MakeShared<FJsonObject>();auto DeclaredDefaults=MakeShared<FJsonObject>();
    UFunction* Function=Call->GetTargetFunction();
    for(UEdGraphPin* Pin:Call->Pins)if(IsArgument(Pin))
    {
        bool NativeDefault=false;
        FString Declared;
        if(Function && DeclarationDefault(Function,Pin->PinName,Declared))
        {
            auto* Normalized=UEdGraphPin::CreatePin(Call);Normalized->PinType=Pin->PinType;Normalized->Direction=EGPD_Input;
            GetDefault<UEdGraphSchema_K2>()->SetPinAutogeneratedDefaultValue(Normalized,Declared);
            DeclaredDefaults->SetStringField(Pin->PinName.ToString(),Normalized->DefaultValue);
            NativeDefault=Pin->DefaultValue==Normalized->DefaultValue && Pin->AutogeneratedDefaultValue==Normalized->AutogeneratedDefaultValue;
            Normalized->MarkAsGarbage();
        }
        // Native nodes have no persistent explicit-equal intent. Keep arithmetic
        // operands visible, but otherwise report the engine's default state.
        if(!NativeDefault || (Function && Function->GetOwnerClass()->GetPathName()==MathLibrary))
            Values->SetStringField(Pin->PinName.ToString(),Pin->DefaultValue);
    }
    Result->SetObjectField(Overrides,Values);Result->SetObjectField(Defaults,DeclaredDefaults);
    return Result;
}
