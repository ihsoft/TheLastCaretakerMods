bool UBlueprintTextCallFunction::IsArgument(const UEdGraphPin* Pin)
{
    if(!Pin || Pin->Direction!=EGPD_Input || Pin->ParentPin || Pin->SubPins.Num() ||
       Pin->PinType.IsContainer() || Pin->PinType.bIsReference || Pin->bDefaultValueIsIgnored ||
       Pin->bOrphanedPin || Pin->PinName==UEdGraphSchema_K2::PN_Self)return false;
    const FName Type=Pin->PinType.PinCategory;
    return Type==UEdGraphSchema_K2::PC_Int || Type==UEdGraphSchema_K2::PC_Int64 ||
        Type==UEdGraphSchema_K2::PC_Real || Type==UEdGraphSchema_K2::PC_Boolean || Type==UEdGraphSchema_K2::PC_String;
}

bool UBlueprintTextCallFunction::DeclarationDefault(const UFunction* Function,FName Name,FString& Value)
{
    const FName Marker(TEXT("BlueprintText.OptionalParameters"));
    if(Function->HasMetaData(Marker))
    {
        TArray<TSharedPtr<FJsonValue>> Names;
        if(!FJsonSerializer::Deserialize(TJsonReaderFactory<>::Create(Function->GetMetaData(Marker)),Names))return false;
        for(const auto& Item:Names)if(Item->AsString()==Name.ToString())
        {Value=Function->GetMetaData(Name);return true;}
        return false;
    }
    // C++ metadata distinguishes an explicitly empty default from no default.
    const FName CppKey(*(TEXT("CPP_Default_")+Name.ToString()));
    if(Function->HasMetaData(CppKey)){Value=Function->GetMetaData(CppKey);return true;}
    Value=Function->GetMetaData(Name);
    // Legacy Blueprint user pins cannot distinguish absent and empty strings.
    // Empty defaults require an explicit parameterDefaults declaration.
    return !Value.IsEmpty();
}

bool UBlueprintTextCallFunction::Arguments(bool bWrite,FString& Error) const
{
    TSharedPtr<FJsonObject> Overrides;
    if(!FJsonSerializer::Deserialize(TJsonReaderFactory<>::Create(BPTArgumentOverrides),Overrides) || !Overrides)
    {Error=TEXT("Invalid BPT argument overrides.");return false;}
    UFunction* Function=GetTargetFunction();
    if(!Function){Error=TEXT("BPT argument declaration is unavailable.");return false;}
    const auto* Schema=GetDefault<UEdGraphSchema_K2>();
    auto Declaration=MakeShared<FJsonObject>();
    for(const auto& Pair:Overrides->Values)
    {
        FString Value;
        if(!IsArgument(FindPin(*Pair.Key,EGPD_Input)) || !Pair.Value->TryGetString(Value))
        {Error=FString::Printf(TEXT("Unsupported BPT argument override: %s"),*Pair.Key);return false;}
    }
    for(UEdGraphPin* Pin:Pins)if(IsArgument(Pin))
    {
        const FProperty* Param=FindFProperty<FProperty>(Function,Pin->PinName);
        FEdGraphPinType Type;
        if(!Param || !Param->HasAnyPropertyFlags(CPF_Parm) || Param->HasAnyPropertyFlags(CPF_OutParm) ||
           !Schema->ConvertPropertyToPinType(Param,Type) || Type!=Pin->PinType)
        {Error=TEXT("BPT argument no longer matches its declaration: ")+Pin->PinName.ToString();return false;}
        // Use an independent pin for normalization; validation must not repair the stored pin.
        UEdGraphPin* Expected=UEdGraphPin::CreatePin(const_cast<UBlueprintTextCallFunction*>(this));
        Expected->PinName=Pin->PinName;Expected->Direction=EGPD_Input;Expected->PinType=Pin->PinType;
        FString Declared;
        const bool HasDefault=DeclarationDefault(Function,Pin->PinName,Declared);
        if(HasDefault)
        {
            Declaration->SetStringField(Pin->PinName.ToString(),Declared);
            Schema->SetPinAutogeneratedDefaultValue(Expected,Declared);
        }
        else Schema->SetPinAutogeneratedDefaultValueBasedOnType(Expected);
        FString Explicit;
        const bool HasOverride=Overrides->TryGetStringField(Pin->PinName.ToString(),Explicit);
        if(!HasDefault && !HasOverride && Pin->LinkedTo.IsEmpty())
        {Expected->MarkAsGarbage();Error=TEXT("Missing required argument (no declaration default): ")+Pin->PinName.ToString();return false;}
        if(HasOverride)
            Schema->GetPinDefaultValuesFromString(Expected->PinType,const_cast<UBlueprintTextCallFunction*>(this),Explicit,
                Expected->DefaultValue,Expected->DefaultObject,Expected->DefaultTextValue);
        const FString Invalid=Schema->IsPinDefaultValid(Expected,Expected->DefaultValue,Expected->DefaultObject,Expected->DefaultTextValue);
        const bool Same=Pin->DefaultValue==Expected->DefaultValue && Pin->DefaultObject==Expected->DefaultObject &&
            Pin->DefaultTextValue.IdenticalTo(Expected->DefaultTextValue) && Pin->AutogeneratedDefaultValue==Expected->AutogeneratedDefaultValue;
        if(bWrite && Invalid.IsEmpty())
        {
            Pin->DefaultValue=Expected->DefaultValue;Pin->DefaultObject=Expected->DefaultObject;
            Pin->DefaultTextValue=Expected->DefaultTextValue;Pin->AutogeneratedDefaultValue=Expected->AutogeneratedDefaultValue;
        }
        Expected->MarkAsGarbage();
        if(!Invalid.IsEmpty() || (!bWrite && !Same))
        {Error=FString::Printf(TEXT("BPT argument %s is invalid or stale; update/recompile the caller. %s"),*Pin->PinName.ToString(),*Invalid);return false;}
    }
    if(bWrite)
    {
        auto* This=const_cast<UBlueprintTextCallFunction*>(this);This->BPTDeclarationDefaults.Reset();
        FJsonSerializer::Serialize(Declaration,TJsonWriterFactory<TCHAR,TCondensedJsonPrintPolicy<TCHAR>>::Create(&This->BPTDeclarationDefaults));
    }
    else
    {
        TSharedPtr<FJsonObject> Stored;
        if(!FJsonSerializer::Deserialize(TJsonReaderFactory<>::Create(BPTDeclarationDefaults),Stored) || !Stored || Stored->Values.Num()!=Declaration->Values.Num())
        {Error=TEXT("BPT declaration snapshot is stale.");return false;}
        for(const auto& Pair:Declaration->Values)
        {
            FString Value;
            if(!Stored->TryGetStringField(Pair.Key,Value) || Value!=Pair.Value->AsString())
            {Error=TEXT("BPT declaration snapshot is stale.");return false;}
        }
    }
    return true;
}
bool UBlueprintTextCallFunction::RefreshArguments(FString& Error)
{
    TGuardValue<bool> Guard(bUpdatingArguments,true);return Arguments(true,Error);
}
bool UBlueprintTextCallFunction::CheckArguments(FString& Error) const {return Arguments(false,Error);}
void UBlueprintTextCallFunction::ReconstructNode()
{
    TGuardValue<bool> Guard(bUpdatingArguments,true);Super::ReconstructNode();
}
void UBlueprintTextCallFunction::PostReconstructNode()
{
    Super::PostReconstructNode();FString Error;RefreshArguments(Error);
}
void UBlueprintTextCallFunction::PinDefaultValueChanged(UEdGraphPin* Pin)
{
    if(!bUpdatingArguments && IsArgument(Pin))
    {
        TSharedPtr<FJsonObject> Overrides;
        if(FJsonSerializer::Deserialize(TJsonReaderFactory<>::Create(BPTArgumentOverrides),Overrides) && Overrides)
        {
            Overrides->SetStringField(Pin->PinName.ToString(),Pin->DefaultValue);
            BPTArgumentOverrides.Reset();
            FJsonSerializer::Serialize(Overrides.ToSharedRef(),TJsonWriterFactory<TCHAR,TCondensedJsonPrintPolicy<TCHAR>>::Create(&BPTArgumentOverrides));
        }
    }
    Super::PinDefaultValueChanged(Pin);
}
void UBlueprintTextCallFunction::ValidateNodeDuringCompilation(FCompilerResultsLog& MessageLog) const
{
    Super::ValidateNodeDuringCompilation(MessageLog);FString Error;
    if(!const_cast<UBlueprintTextCallFunction*>(this)->RefreshArguments(Error))MessageLog.Error(*FString::Printf(TEXT("@@ %s"),*Error),this);
}
