"""Native call template boundary: scoped requests, exact metadata and no source writes."""
import copy
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

import blueprint_workspace as bw
from asset_text_codec import add_call, compact, template
from test_asset_text_codec import fixture


OPERATION = '/Script/Engine.BoxComponent::SetBoxExtent'


def catalog():
    insertion = '\n'.join([
        'Begin Object Class=/Script/BlueprintGraph.K2Node_CallFunction Name="Call"',
        'FunctionReference=(MemberParent="/Script/Engine.BoxComponent",MemberName="SetBoxExtent")',
        'CustomProperties Pin (PinId=' + 'A'*32 + ',PinName="bUpdateOverlaps",PinType.PinCategory="bool",DefaultValue="true",AutogeneratedDefaultValue="true",)',
        'CustomProperties Pin (PinId=' + 'B'*32 + ',PinName="Required",PinType.PinCategory="struct",PinType.bIsReference=True,PinType.bIsConst=True,bDefaultValueIsIgnored=True,)',
        'End Object'])
    return dict(schema=1, contextParent='/Script/Engine.Actor', engineVersion='test', entries=[dict(
        identity=OPERATION, nativeInsertion=insertion, pure=False, requiredConnections=['Required'], declarationDefaults={'bUpdateOverlaps':'true'})])


class CallTemplateTests(unittest.TestCase):
    def setUp(self):
        bw.OWNER.mkdir(parents=True, exist_ok=True)
        self.temp = tempfile.TemporaryDirectory(dir=bw.OWNER)
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.project = self.root / 'Project/Test.uproject'
        bw.write(self.project, {})
        self.ws = bw.Workspace(self.root / 'workspace', self.root / 'Engine')
        self.source = self.ws.root / 'blueprints/BP_Test.json'
        bw.write(self.source, compact(fixture()))
        bw.write(self.ws.manifest, dict(schema=1, project=str(self.project), assets=[dict(source='blueprints/BP_Test.json')]))

    def test_request_is_batched_and_sources_are_unchanged(self):
        original = self.source.read_bytes(), self.ws.manifest.read_bytes()
        def engine(mode, name, **fields):
            self.assertEqual(mode, 'CallTemplates')
            self.assertEqual(bw.read(fields['Input']), dict(operations=[OPERATION], contextParent='/Script/Engine.Actor'))
            bw.write(fields['Output'], catalog())
        with patch.object(self.ws, 'prepare'), patch.object(self.ws, 'engine_run', side_effect=engine):
            result = self.ws.call_templates([OPERATION])
        self.assertEqual(result['operations'], [dict(identity=OPERATION, pure=False, requiredConnections=['Required'])])
        self.assertTrue(Path(result['catalog']).is_file())
        self.assertEqual((self.source.read_bytes(), self.ws.manifest.read_bytes()), original)

    def test_invalid_operations_and_ambiguous_asset_fail_before_engine(self):
        with patch.object(self.ws, 'prepare') as prepare, patch.object(self.ws, 'engine_run') as engine:
            for operations in (None, [], [OPERATION, OPERATION], ['/Game/BP::Call'], ['bad']):
                with self.subTest(operations=operations), self.assertRaises(ValueError):
                    self.ws.call_templates(operations)
            with self.assertRaises(ValueError):
                self.ws.call_templates([OPERATION], '/Game/Missing')
            second = bw.read(self.source); second['asset'] = '/Game/Other'
            bw.write(self.ws.root / 'blueprints/Other.json', second)
            bw.write(self.ws.manifest, dict(schema=1, project=str(self.project), assets=[
                dict(source='blueprints/BP_Test.json'), dict(source='blueprints/Other.json')]))
            with self.assertRaises(ValueError):
                self.ws.call_templates([OPERATION])
        prepare.assert_not_called(); engine.assert_not_called()

    def test_library_class_identity_reaches_reflection_without_source_changes(self):
        operation = '/Game/Shared/Types.Library_C::IsLarge'
        reflected = catalog(); reflected['entries'][0]['identity'] = operation
        original = self.source.read_bytes()
        def engine(mode, name, **fields):
            self.assertEqual(bw.read(fields['Input'])['operations'], [operation])
            bw.write(fields['Output'], reflected)
        with patch.object(self.ws, 'prepare'), patch.object(self.ws, 'engine_run', side_effect=engine):
            self.assertEqual(self.ws.call_templates([operation])['operations'][0]['identity'], operation)
        self.assertEqual(self.source.read_bytes(), original)

    def test_engine_failure_never_produces_success_or_rewrites_source(self):
        original = self.source.read_bytes()
        with patch.object(self.ws, 'prepare'), patch.object(self.ws, 'engine_run', side_effect=RuntimeError('unsupported')):
            with self.assertRaisesRegex(RuntimeError, 'unsupported'):
                self.ws.call_templates([OPERATION])
        self.assertEqual(self.source.read_bytes(), original)

    def test_factory_preserves_reflection_defaults_and_required_reference_flags(self):
        reflected = catalog(); original = copy.deepcopy(reflected)
        item = template(reflected, OPERATION, 'SetExtent')
        self.assertEqual(item['contextParent'], reflected['contextParent'])
        pin = item['node']['pins']['in:bUpdateOverlaps']
        self.assertEqual(item['pinTemplates'][pin['type']]['AutogeneratedDefaultValue'], '"true"')
        self.assertEqual(item['node']['arguments'], {})
        item['node']['arguments']['in:bUpdateOverlaps'] = 'false'
        required = item['pinTemplates'][item['node']['pins']['in:Required']['type']]
        self.assertEqual(required['PinType.bIsReference'], 'True')
        self.assertEqual(required['bDefaultValueIsIgnored'], 'True')
        second = template(reflected, OPERATION, 'AnotherExtent')
        self.assertNotEqual(pin['id'], second['node']['pins']['in:bUpdateOverlaps']['id'])
        self.assertEqual(reflected, original)

    def test_factory_rejects_wrong_parent_without_breaking_old_catalogs(self):
        document = compact(fixture()); reflected = catalog()
        add_call(document, reflected, OPERATION, 'SetExtent', 'Calculate')
        reflected['contextParent'] = '/Script/CoreUObject.Object'
        with self.assertRaisesRegex(ValueError, 'parent context'):
            add_call(document, reflected, OPERATION, 'SetExtent', 'Calculate')
        del reflected['contextParent']
        add_call(document, reflected, OPERATION, 'SetExtent', 'Calculate')


if __name__ == '__main__':
    unittest.main()
